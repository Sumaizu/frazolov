export const STORIES = FRAMES;

const RECENT_KEEP = 300;
const ATTEMPTS = 40;
const PLACE_RE = /\{([a-z]+)(?:\.(\d))?\}/g;

export const norm = (text) => String(text == null ? '' : text).trim().toLowerCase().replace(/ё/g, 'е');

export const pick = (rng, list) => list[Math.floor(rng() * list.length)];

export function variants(story) {
  return Object.values(story.slots).reduce((product, options) => product * options.length, 1);
}

export function compose(story, number) {
  const values = new Map();
  for (const [name, options] of Object.entries(story.slots)) {
    const option = options[number % options.length];
    number = Math.floor(number / options.length);
    values.set(name, Array.isArray(option) ? option : [option]);
  }
  const fill = (whole, name, form) => values.get(name)[Number(form || 0)];
  return story.text.map((sentence) => sentence.replace(PLACE_RE, fill));
}

export class Phrases {
  constructor(storage = null, key = 'frazolov.recent', rng = Math.random, stories = STORIES) {
    this.storage = storage;
    this.key = key;
    this.rng = rng;
    this.stories = stories;
    this.previous = -1;
    this.recent = [];
    if (!storage) return;
    try {
      const saved = JSON.parse(storage.getItem(key) || '[]');
      if (Array.isArray(saved)) this.recent = saved.filter((line) => typeof line === 'string').slice(-RECENT_KEEP);
    } catch (error) {
      this.recent = [];
    }
  }

  next() {
    const seen = new Set(this.recent);
    const order = this.stories.map((story, index) => index).filter((index) => index !== this.previous);
    for (let i = order.length - 1; i > 0; i--) {
      const j = Math.floor(this.rng() * (i + 1));
      const swap = order[i];
      order[i] = order[j];
      order[j] = swap;
    }
    let text = null, chosen = order[0];
    for (const index of order) {
      const story = this.stories[index], count = variants(story);
      for (let attempt = 0; attempt < Math.min(ATTEMPTS, count * 3); attempt++) {
        const candidate = compose(story, Math.floor(this.rng() * count));
        if (seen.has(candidate.join('|'))) continue;
        text = candidate;
        chosen = index;
        break;
      }
      if (text) break;
    }
    if (!text) text = compose(this.stories[chosen], Math.floor(this.rng() * variants(this.stories[chosen])));
    this.previous = chosen;
    this._remember(text.join('|'));
    return text;
  }

  _remember(line) {
    this.recent = this.recent.filter((other) => other !== line);
    this.recent.push(line);
    while (this.recent.length > RECENT_KEEP) this.recent.shift();
    if (!this.storage) return;
    try {
      this.storage.setItem(this.key, JSON.stringify(this.recent));
    } catch (error) {
      this.storage = null;
    }
  }
}

export function masked(word, known) {
  return Array.from(word, (letter) => (known.has(norm(letter)) ? letter : ' ')).join('');
}
