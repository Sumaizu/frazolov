const ATTEMPTS = 40;

export const norm = (text) => String(text == null ? '' : text).trim().toLowerCase().replace(/ё/g, 'е');

export const pick = (rng, list) => list[Math.floor(rng() * list.length)];

export class Phrases {
  constructor(storage = null, key = 'frazolov.recent', rng = Math.random, texts = TEXTS) {
    this.storage = storage;
    this.key = key;
    this.rng = rng;
    this.texts = texts;
    this.keep = Math.max(0, Math.ceil(texts.length * 0.75));
    this.recent = [];
    if (!storage) return;
    try {
      const saved = JSON.parse(storage.getItem(key) || '[]');
      if (Array.isArray(saved)) this.recent = saved.filter((line) => typeof line === 'string').slice(-this.keep);
    } catch (error) {
      this.recent = [];
    }
  }

  next() {
    const seen = new Set(this.recent);
    let text = pick(this.rng, this.texts);
    for (let attempt = 0; attempt < ATTEMPTS && seen.has(text[0]); attempt++) text = pick(this.rng, this.texts);
    if (seen.has(text[0])) text = this.texts.find((candidate) => !seen.has(candidate[0])) || text;
    this._remember(text[0]);
    return text.slice();
  }

  _remember(first) {
    this.recent = this.recent.filter((line) => line !== first);
    this.recent.push(first);
    while (this.recent.length > this.keep) this.recent.shift();
    if (!this.storage) return;
    try {
      this.storage.setItem(this.key, JSON.stringify(this.recent));
    } catch (error) {
      this.storage = null;
    }
  }
}

export function masked(word, known) {
  return Array.from(word, (letter) => (known.has(norm(letter)) ? letter : ' ')).join('');
}
